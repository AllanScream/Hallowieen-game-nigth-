# v11: the contacts' answers (art/i18n/dm_v11.py) → live/sim.js (const DMT between the DMT markers, Russian only; Elf's lines rewritten)
# and art/i18n/en_c.py (English pairs for tools/i18n_build.py). Run again after editing dm_v11.py.
import json, re, sys
sys.path.insert(0, 'art/i18n')
from dm_v11 import DM, ELF
from dm_v12 import DM2, HINT                                             # v12: more answers, new intents; merged over v11
def merge(a, b):
    if isinstance(a, list) and isinstance(b, list): return a + b
    if isinstance(a, dict) and isinstance(b, dict): return {k: merge(a[k], b[k]) if k in a and k in b else (a.get(k) or b.get(k)) for k in list(a) + [k for k in b if k not in a]}
    if isinstance(a, list): return {k: a + v for k, v in b.items()} | ({'def': a + b.get('def', [])})
    return {k: v + b for k, v in a.items()}
for w, t in DM2.items():
    DM.setdefault(w, {})
    for i, v in t.items(): DM[w][i] = merge(DM[w][i], v) if i in DM[w] else v
p = 'live/sim.js'; s = open(p, encoding='utf-8').read()
for i, (old, new, _) in enumerate(ELF):                                # idempotent: lines already rewritten stay as they are
    s = s.replace(new, '\x00%d\x00' % i)
    if old in s: s = s.replace(old, new)
    s = s.replace('\x00%d\x00' % i, new)
def ru(v): return [l[0] for l in v] if isinstance(v, list) else {k: ru(x) for k, x in v.items()}
js = '  const DMT = ' + json.dumps({w: {i: ru(v) for i, v in t.items()} for w, t in DM.items()}, ensure_ascii=False, separators=(',', ':')) + ';'
s = re.sub(r'  // DMT-BEGIN\n(?:.*?\n)?  // DMT-END', lambda m: '  // DMT-BEGIN\n' + js + '\n  // DMT-END', s, flags=re.S)
assert 'const DMT = ' in s, 'markers missing'
open(p, 'w', encoding='utf-8').write(s)
pairs = []
def walk(v):
    if isinstance(v, list): pairs.extend(v)
    else: [walk(x) for x in v.values()]
for t in DM.values():
    for v in t.values(): walk(v)
pairs += [[n, e] for _, n, e in ELF] + HINT
pairs += [[re.sub(r'^(Кирилл|Райва|Эльф): ', '', r), re.sub(r'^(Kirill|Raiva|Elf): ', '', e)] for r, e in list(pairs) if re.match(r'^(Кирилл|Райва|Эльф): ', r)]   # group replies are stored without the name
open('art/i18n/en_c.py', 'w', encoding='utf-8').write('# generated by tools/dm_build.py from dm_v11.py\nEXTRA = ' + json.dumps(pairs, ensure_ascii=False, indent=0) + '\n')
print(len(pairs), 'pairs')
