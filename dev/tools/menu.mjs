// Main menu + pause + phone text field, as the player uses them: node tools/menu.mjs [dir] [outDir]
// dir: live (default) or dist/halloween/game. Screenshots: 1_menu, 2_settings, 3_play, 4_pause, 5_console, 6_continue.
import http from 'node:http'; import fs from 'node:fs'; import path from 'node:path'; import { createRequire } from 'node:module';
const { chromium } = createRequire(import.meta.url)('/root/.cache/ref2game/claude/scripts/node_modules/playwright');
const [dir = 'live', out = 'frames/menu'] = process.argv.slice(2); fs.mkdirSync(out, { recursive: true });
const types = { '.html': 'text/html', '.js': 'text/javascript', '.png': 'image/png', '.webp': 'image/webp' };
const srv = http.createServer((q, r) => { const f = path.join(dir, decodeURIComponent(q.url.split('?')[0]));
  fs.stat(f, (e) => { if (e) { r.writeHead(404); r.end(); return; } r.writeHead(200, { 'content-type': types[path.extname(f)] || 'application/octet-stream', 'last-modified': 'x' }); fs.createReadStream(f).pipe(r); }); });
await new Promise((r) => srv.listen(0, '127.0.0.1', r));
const b = await chromium.launch({ args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader'] });
const p = await b.newPage({ viewport: { width: 1280, height: 720 } });
const errs = []; p.on('pageerror', (e) => errs.push(e.message)); p.on('console', (m) => { if (m.type() === 'error') errs.push(m.text()); });
const url = `http://127.0.0.1:${srv.address().port}/index.html`;
await p.goto(url);
await p.waitForFunction(() => window.__ready, null, { timeout: 90000 }); await p.waitForTimeout(800);
const st = () => p.evaluate(() => { const s = SCENE.state; return s ? { x: Math.round(s.x), y: Math.round(s.y), money: s.money, phone: s.phone && s.phone.app, log: (s.devLog || []).slice(-2).map((m) => m.text) } : null; });
await p.screenshot({ path: out + '/1_menu.png' });
console.log('menu: new disabled', await p.$eval('#m_new', (e) => e.disabled), 'cont disabled', await p.$eval('#m_cont', (e) => e.disabled));
await p.click('#mainBtns [data-panel=p_set]'); await p.waitForTimeout(400); await p.screenshot({ path: out + '/2_settings.png' });
await p.keyboard.press('Escape'); await p.waitForTimeout(200);
await p.click('#m_new'); await p.waitForTimeout(2500);
console.log('play', JSON.stringify(await st()));
console.log('frame ms', await p.evaluate(() => new Promise((r) => { let n = 0; const t0 = performance.now(); const f = () => { if (++n < 4) requestAnimationFrame(f); else r(Math.round((performance.now() - t0) / 4)); }; requestAnimationFrame(f); })));
await p.keyboard.down('KeyS'); await p.waitForTimeout(4000); await p.keyboard.up('KeyS'); await p.waitForTimeout(500);
console.log('after walk', JSON.stringify(await st()));
await p.screenshot({ path: out + '/3_play.png' });
const W = (fn, arg) => p.waitForFunction(fn, arg, { timeout: 120000 });
const hold = async (key, fn) => { await p.keyboard.down(key); await W(fn); await p.keyboard.up(key); };
await p.keyboard.press('Escape'); await p.waitForTimeout(600); await p.screenshot({ path: out + '/4_pause.png' });
console.log('saved', await p.evaluate(() => { const s = localStorage.getItem('sog_save'); return s ? s.length + ' bytes' : 'none'; }));
await p.click('#p_resume'); await p.waitForTimeout(400);
await hold('Tab', () => SCENE.state && SCENE.state.phone);
const dev = await p.evaluate(() => { const L = SIM.phoneLayout(SCENE.state).find((b) => b.id === 'dev'), r = document.getElementById('c').getBoundingClientRect(); return [r.left + (L.x + L.w / 2) / 1920 * r.width, r.top + (L.y + L.h / 2) / 1080 * r.height]; });
await p.mouse.click(dev[0], dev[1]); await W(() => document.getElementById('txt').style.display === 'block'); await p.waitForTimeout(300);
console.log('field', await p.$eval('#txt', (e) => e.style.display + ' focused=' + (document.activeElement === e)));
await p.keyboard.type('money 777'); await p.keyboard.press('Enter');
await p.keyboard.type('give eggs 5'); await p.keyboard.press('Enter');
await W(() => SCENE.state.devLog.length >= 5);
console.log('console', JSON.stringify(await st()));
await p.screenshot({ path: out + '/5_console.png' });
await p.keyboard.press('Escape'); await hold('Escape', () => !SCENE.state.phone); await p.waitForTimeout(300);
await p.keyboard.press('Escape'); await p.waitForTimeout(400);
await p.click('#p_save'); await p.waitForTimeout(300);
await p.fill('#slotList .slot:nth-child(2) .sl-name', 'Перед Кириллом'); await p.click('#slotList .slot:nth-child(2) .sbtn'); await p.waitForTimeout(300);
console.log('slot saved:', await p.$eval('#slotMsg', (e) => e.textContent), '|', await p.$eval('#slotList .slot:nth-child(2) .sl-meta', (e) => e.textContent));
await p.screenshot({ path: out + '/5b_save.png' });
await p.click('#p_save ~ .x, #p_saves .back').catch(() => {}); await p.waitForTimeout(200);
await p.click('#p_exit'); await p.waitForTimeout(500);
await p.click('#m_load'); await p.waitForTimeout(300); await p.screenshot({ path: out + '/5c_load.png' });
console.log('load list:', JSON.stringify(await p.$$eval('#slotList .slot', (els) => els.map((e) => e.querySelector('.sl-name').value + ' / ' + e.querySelector('.sl-meta').textContent))));
await p.keyboard.press('Escape'); await p.waitForTimeout(200);
console.log('back in menu: cont disabled', await p.$eval('#m_cont', (e) => e.disabled), 'note', await p.$eval('#contNote', (e) => e.textContent));
await p.click('#m_cont'); await W(() => SCENE.state); await p.waitForTimeout(500);
console.log('continued', JSON.stringify(await st()));
await p.screenshot({ path: out + '/6_continue.png' });
console.log('errors', JSON.stringify(errs));
await b.close(); srv.close();
